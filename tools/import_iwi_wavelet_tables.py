"""Reproduce only immutable numerical wavelet codebooks; never import a runtime."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "src/ObjImage/Image/IwiWaveletDecoder.cpp"
TABLES = {"blue": ("BLUE", 180), "red_green": ("RED_GREEN", 80), "alpha": ("ALPHA", 108)}


def codebooks(text: str) -> dict:
    result = {}
    for name, (symbol, count) in TABLES.items():
        match = re.search(rf"{symbol}_CODEWORDS = .*?\(\{{(.*?)\}}\);", text, re.S)
        if match is None:
            raise SystemExit("Missing immutable wavelet codebook")
        rows = [(int(code, 16), int(bits), -32768 if value == "ESCAPE_VALUE" else int(value))
                for code, bits, value in re.findall(
                    r"\{(0x[0-9A-Fa-f]+),\s*(\d+),\s*(-?\d+|ESCAPE_VALUE)\}", match[1])]
        if len(rows) != count:
            raise SystemExit("Wavelet codebook count mismatch")
        coverage = [False] * 4096
        for code, bits, _ in rows:
            if not 1 <= bits <= 12 or not 0 <= code < (1 << bits):
                raise SystemExit("Invalid wavelet codeword")
            for index in range(code, 4096, 1 << bits):
                if coverage[index]:
                    raise SystemExit("Overlapping wavelet codewords")
                coverage[index] = True
        if not all(coverage):
            raise SystemExit("Incomplete wavelet codebook")
        result[name] = rows
    return result


def pinned_source() -> bytes:
    record = json.loads((ROOT / "docs/iwi-format-sources.json").read_text(encoding="utf-8"))
    revision = record["revision"]
    if (record["repository"] != "https://github.com/Laupetin/OpenAssetTools"
            or not re.fullmatch(r"[0-9a-f]{40}", revision)):
        raise SystemExit("Invalid immutable wavelet source identity")
    url = f"https://raw.githubusercontent.com/Laupetin/OpenAssetTools/{revision}/{SOURCE}"
    with urllib.request.urlopen(url, timeout=20) as response:
        data = response.read(256 * 1024 + 1).replace(b"\r\n", b"\n")
    if len(data) > 256 * 1024 or hashlib.sha256(data).hexdigest() != record["sources"][SOURCE]:
        raise SystemExit("Immutable wavelet source size/hash mismatch")
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Write generated numerical tables")
    args = parser.parse_args()
    data = pinned_source()
    for name, rows in codebooks(data.decode("utf-8")).items():
        lines = ["// SPDX-License-Identifier: GPL-3.0-only",
                 "// Numerical codebook derived from OpenAssetTools contributors; see NOTICE.",
                 "// Generated by tools/import_iwi_wavelet_tables.py; do not edit.",
                 "use super::super::entropy::Codeword;", "",
                 f"pub(in crate::iwi6::wavelet) const WORDS: [Codeword; {len(rows)}] = ["]
        lines.extend(f"    Codeword(0x{code:03x}, {bits}, {value})," for code, bits, value in rows)
        expected = "\n".join([*lines, "];", ""])
        path = ROOT / f"crates/content/src/iwi6/wavelet/tables/{name}.rs"
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8", newline="\n")
        elif path.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"Generated wavelet catalog differs: {name}")
    print("Reproduced three complete wavelet codebooks (368 codewords)")


if __name__ == "__main__":
    main()
